#include "xcc.h"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

static int align16(int n) {
    return (n + 15) & ~15;
}

static int align_up(int n, int a) {
    if (a <= 1) return n;
    return (n + a - 1) & ~(a - 1);
}

static int vreg_offset(int vreg_base_offset, int vreg) {
    return vreg_base_offset + (vreg + 1) * 8;
}

static void emit_escaped_bytes(FILE *out, const char *data, int len) {
    fprintf(out, "  .asciz \"");
    for (int i = 0; i < len; i++) {
        unsigned char c = (unsigned char)data[i];
        if (c == '\n') fprintf(out, "\\n");
        else if (c == '\t') fprintf(out, "\\t");
        else if (c == '\r') fprintf(out, "\\r");
        else if (c == '"') fprintf(out, "\\\"");
        else if (c == '\\') fprintf(out, "\\\\");
        else if (c >= 32 && c < 127) fprintf(out, "%c", c);
        else fprintf(out, "\\%03o", c);
    }
    fprintf(out, "\"\n");
}

void emit_x86_64_asm(const IRProgram *ir, const TargetInfo *target, FILE *out) {
    fprintf(out, "# Generated by XCC for target: %s (%s)\n", target->name, target->triple);

    /* 1. String Literals (Plaintext vs Obfuscated Encrypted Byte Blobs) */
    if (ir->strings) {
        bool has_plain = false;
        bool has_enc = false;
        for (const StringLiteral *s = ir->strings; s; s = s->next) {
            if (s->is_encrypted) has_enc = true;
            else has_plain = true;
        }
        if (has_plain) {
            if (target->is_macos) {
                fprintf(out, "  .section __TEXT,__cstring,cstring_literals\n");
            } else if (target->is_windows) {
                fprintf(out, "  .section .rdata,\"dr\"\n");
            } else {
                fprintf(out, "  .section .rodata\n");
            }
            for (const StringLiteral *s = ir->strings; s; s = s->next) {
                if (s->is_encrypted) continue;
                fprintf(out, ".L.str.%d:\n", s->id);
                emit_escaped_bytes(out, s->data, s->len);
            }
            fprintf(out, "\n");
        }
        if (has_enc) {
            if (target->is_macos) {
                fprintf(out, "  .section __TEXT,__const\n");
            } else if (target->is_windows) {
                fprintf(out, "  .section .rdata,\"dr\"\n");
            } else {
                fprintf(out, "  .section .rodata\n");
            }
            for (const StringLiteral *s = ir->strings; s; s = s->next) {
                if (!s->is_encrypted) continue;
                fprintf(out, ".L.str.%d:\n", s->id);
                for (int i = 0; i <= s->len; i++) {
                    unsigned char b = (i < s->len) ? (unsigned char)s->data[i] : 0;
                    fprintf(out, "  .byte 0x%02x\n", b);
                }
            }
            fprintf(out, "\n");
        }
    }

    /* 2. Global Variables */
    for (const VarObj *g = ir->globals; g; g = g->next) {
        if (g->type->kind == TY_FUNC || g->is_extern) continue;
        int align_pow = 3;
        if (g->type->align <= 1) align_pow = 0;
        else if (g->type->align <= 2) align_pow = 1;
        else if (g->type->align <= 4) align_pow = 2;

        if (!g->has_init) {
            if (target->is_macos) {
                if (g->is_static) {
                    fprintf(out, "  .lcomm %s%s, %d, %d\n",
                            target->symbol_prefix, g->name, g->type->size, align_pow);
                } else {
                    fprintf(out, "  .comm %s%s, %d, %d\n",
                            target->symbol_prefix, g->name, g->type->size, align_pow);
                }
            } else {
                fprintf(out, "  .bss\n");
                if (!g->is_static) fprintf(out, "  .globl %s%s\n", target->symbol_prefix, g->name);
                fprintf(out, "  .p2align %d\n", align_pow);
                fprintf(out, "%s%s:\n", target->symbol_prefix, g->name);
                fprintf(out, "  .zero %d\n", g->type->size);
            }
            continue;
        }

        fprintf(out, "  .data\n");
        if (!g->is_static) {
            fprintf(out, "  .globl %s%s\n", target->symbol_prefix, g->name);
        }
        fprintf(out, "  .p2align %d\n", align_pow);
        fprintf(out, "%s%s:\n", target->symbol_prefix, g->name);

        int cur_off = 0;
        for (const GlobalInit *gi = g->init_list; gi; gi = gi->next) {
            if (gi->offset > cur_off) {
                fprintf(out, "  .zero %d\n", gi->offset - cur_off);
                cur_off = gi->offset;
            }
            if (gi->label) {
                bool is_str = (strncmp(gi->label, ".L.str.", 7) == 0);
                const char *pfx = is_str ? "" : target->symbol_prefix;
                if (gi->addend != 0) {
                    fprintf(out, "  .quad %s%s + %lld\n", pfx, gi->label, (long long)gi->addend);
                } else {
                    fprintf(out, "  .quad %s%s\n", pfx, gi->label);
                }
                cur_off += 8;
            } else {
                switch (gi->size) {
                    case 1: fprintf(out, "  .byte %lld\n", (long long)(gi->val & 0xFF)); break;
                    case 2: fprintf(out, "  .short %lld\n", (long long)(gi->val & 0xFFFF)); break;
                    case 4: fprintf(out, "  .long %lld\n", (long long)(gi->val & 0xFFFFFFFF)); break;
                    default: fprintf(out, "  .quad %lld\n", (long long)gi->val); break;
                }
                cur_off += gi->size;
            }
        }
        if (cur_off < g->type->size) {
            fprintf(out, "  .zero %d\n", g->type->size - cur_off);
        }
        fprintf(out, "\n");
    }

    /* 3. Functions */
    fprintf(out, "  .text\n");

    static const char *sysv_arg_regs64[6] = {"%rdi", "%rsi", "%rdx", "%rcx", "%r8", "%r9"};
    static const char *win64_arg_regs64[4] = {"%rcx", "%rdx", "%r8", "%r9"};

    for (IRFunc *fn = ir->funcs; fn; fn = fn->next) {
        int offset = 0;
        for (int i = 0; i < fn->local_count; i++) {
            int sz = fn->locals[i].size > 0 ? fn->locals[i].size : 8;
            int al = fn->locals[i].align > 0 ? fn->locals[i].align : 8;
            offset += sz;
            offset = align_up(offset, al);
            fn->locals[i].stack_offset = offset;
        }
        offset = align_up(offset, 8);
        int vreg_base = offset;
        int total_frame = align16(vreg_base + fn->vreg_count * 8);

        if (!fn->is_static) {
            fprintf(out, "  .globl %s%s\n", target->symbol_prefix, fn->name);
        }
        fprintf(out, "  .p2align 4\n");
        fprintf(out, "%s%s:\n", target->symbol_prefix, fn->name);

        /* Prologue */
        fprintf(out, "  pushq %%rbp\n");
        fprintf(out, "  movq %%rsp, %%rbp\n");
        if (total_frame > 0) {
            fprintf(out, "  subq $%d, %%rsp\n", total_frame);
        }

        /* Save incoming parameters into their local slots */
        int max_reg_params = target->is_windows ? 4 : 6;
        const char **arg_regs = target->is_windows ? win64_arg_regs64 : sysv_arg_regs64;

        for (int i = 0; i < fn->param_count; i++) {
            int slot_id = fn->param_local_ids[i];
            int slot_off = fn->locals[slot_id].stack_offset;
            int psize = fn->param_sizes[i];
            if (i < max_reg_params) {
                fprintf(out, "  movq %s, %%rax\n", arg_regs[i]);
            } else {
                int caller_off = target->is_windows ? (16 + 32 + (i - 4) * 8) : (16 + (i - 6) * 8);
                fprintf(out, "  movq %d(%%rbp), %%rax\n", caller_off);
            }
            if (psize == 1) fprintf(out, "  movb %%al, -%d(%%rbp)\n", slot_off);
            else if (psize == 2) fprintf(out, "  movw %%ax, -%d(%%rbp)\n", slot_off);
            else if (psize == 4) fprintf(out, "  movl %%eax, -%d(%%rbp)\n", slot_off);
            else fprintf(out, "  movq %%rax, -%d(%%rbp)\n", slot_off);
        }

        int pending_args[64];
        int pending_arg_count = 0;

        for (int i = 0; i < fn->inst_count; i++) {
            const IRInst *in = &fn->insts[i];
            switch (in->op) {
                case IR_NOP:
                    break;

                case IR_LABEL:
                    fprintf(out, ".L%d:\n", in->label);
                    break;

                case IR_IMM:
                    fprintf(out, "  movabsq $%lld, %%rax\n", (long long)in->imm);
                    fprintf(out, "  movq %%rax, -%d(%%rbp)\n", vreg_offset(vreg_base, in->dst));
                    break;

                case IR_OBF_IMM: {
                    int dst_off = vreg_offset(vreg_base, in->dst);
                    fprintf(out, "  movabsq $%lld, %%rax\n", (long long)in->imm);
                    fprintf(out, "  movq %%rax, -%d(%%rbp)\n", dst_off);
                    fprintf(out, "  movabsq $%lld, %%rcx\n", (long long)in->obf_key);
                    fprintf(out, "  movq %%rcx, %%rdx\n");
                    fprintf(out, "  shrq $17, %%rdx\n");
                    fprintf(out, "  movq -%d(%%rbp), %%rax\n", dst_off);
                    fprintf(out, "  xorq %%rdx, %%rax\n");
                    fprintf(out, "  subq %%rcx, %%rax\n");
                    fprintf(out, "  movabsq $%lld, %%rdx\n", (long long)in->obf_rot);
                    fprintf(out, "  xorq %%rdx, %%rax\n");
                    fprintf(out, "  movq %%rax, -%d(%%rbp)\n", dst_off);
                    break;
                }

                case IR_STR_ADDR:
                    fprintf(out, "  leaq .L.str.%lld(%%rip), %%rax\n", (long long)in->imm);
                    fprintf(out, "  movq %%rax, -%d(%%rbp)\n", vreg_offset(vreg_base, in->dst));
                    break;

                case IR_LOCAL_ADDR:
                    fprintf(out, "  leaq -%d(%%rbp), %%rax\n", fn->locals[in->imm].stack_offset);
                    fprintf(out, "  movq %%rax, -%d(%%rbp)\n", vreg_offset(vreg_base, in->dst));
                    break;

                case IR_GLOBAL_ADDR:
                    if (target->is_macos) {
                        fprintf(out, "  movq %s%s@GOTPCREL(%%rip), %%rax\n",
                                target->symbol_prefix, in->sym_name);
                    } else {
                        fprintf(out, "  leaq %s%s(%%rip), %%rax\n",
                                target->symbol_prefix, in->sym_name);
                    }
                    fprintf(out, "  movq %%rax, -%d(%%rbp)\n", vreg_offset(vreg_base, in->dst));
                    break;

                case IR_MOV:
                    fprintf(out, "  movq -%d(%%rbp), %%rax\n", vreg_offset(vreg_base, in->src1));
                    fprintf(out, "  movq %%rax, -%d(%%rbp)\n", vreg_offset(vreg_base, in->dst));
                    break;

                case IR_LOAD:
                    fprintf(out, "  movq -%d(%%rbp), %%rcx\n", vreg_offset(vreg_base, in->src1));
                    if (in->mem_size == 1) {
                        fprintf(out, "  %s (%%rcx), %%rax\n", in->is_unsigned ? "movzbq" : "movsbq");
                    } else if (in->mem_size == 2) {
                        fprintf(out, "  %s (%%rcx), %%rax\n", in->is_unsigned ? "movzwq" : "movswq");
                    } else if (in->mem_size == 4) {
                        if (in->is_unsigned) fprintf(out, "  movl (%%rcx), %%eax\n");
                        else fprintf(out, "  movslq (%%rcx), %%rax\n");
                    } else {
                        fprintf(out, "  movq (%%rcx), %%rax\n");
                    }
                    fprintf(out, "  movq %%rax, -%d(%%rbp)\n", vreg_offset(vreg_base, in->dst));
                    break;

                case IR_STORE:
                    fprintf(out, "  movq -%d(%%rbp), %%rcx\n", vreg_offset(vreg_base, in->src1));
                    fprintf(out, "  movq -%d(%%rbp), %%rax\n", vreg_offset(vreg_base, in->src2));
                    if (in->mem_size == 1) fprintf(out, "  movb %%al, (%%rcx)\n");
                    else if (in->mem_size == 2) fprintf(out, "  movw %%ax, (%%rcx)\n");
                    else if (in->mem_size == 4) fprintf(out, "  movl %%eax, (%%rcx)\n");
                    else fprintf(out, "  movq %%rax, (%%rcx)\n");
                    break;

                case IR_MEMCPY:
                    fprintf(out, "  movq -%d(%%rbp), %%rdx\n", vreg_offset(vreg_base, in->src1));
                    fprintf(out, "  movq -%d(%%rbp), %%rcx\n", vreg_offset(vreg_base, in->src2));
                    for (int b = 0; b < (int)in->imm; b++) {
                        fprintf(out, "  movb %d(%%rcx), %%al\n", b);
                        fprintf(out, "  movb %%al, %d(%%rdx)\n", b);
                    }
                    break;

                case IR_NEG:
                    fprintf(out, "  movq -%d(%%rbp), %%rax\n", vreg_offset(vreg_base, in->src1));
                    fprintf(out, "  negq %%rax\n");
                    fprintf(out, "  movq %%rax, -%d(%%rbp)\n", vreg_offset(vreg_base, in->dst));
                    break;

                case IR_BITNOT:
                    fprintf(out, "  movq -%d(%%rbp), %%rax\n", vreg_offset(vreg_base, in->src1));
                    fprintf(out, "  notq %%rax\n");
                    fprintf(out, "  movq %%rax, -%d(%%rbp)\n", vreg_offset(vreg_base, in->dst));
                    break;

                case IR_LOGNOT:
                    fprintf(out, "  movq -%d(%%rbp), %%rax\n", vreg_offset(vreg_base, in->src1));
                    fprintf(out, "  cmpq $0, %%rax\n");
                    fprintf(out, "  sete %%al\n");
                    fprintf(out, "  movzbq %%al, %%rax\n");
                    fprintf(out, "  movq %%rax, -%d(%%rbp)\n", vreg_offset(vreg_base, in->dst));
                    break;

                case IR_CAST:
                    fprintf(out, "  movq -%d(%%rbp), %%rax\n", vreg_offset(vreg_base, in->src1));
                    if (in->mem_size == 1) {
                        fprintf(out, "  %s %%al, %%rax\n", in->is_unsigned ? "movzbq" : "movsbq");
                    } else if (in->mem_size == 2) {
                        fprintf(out, "  %s %%ax, %%rax\n", in->is_unsigned ? "movzwq" : "movswq");
                    } else if (in->mem_size == 4) {
                        if (in->is_unsigned) fprintf(out, "  movl %%eax, %%eax\n");
                        else fprintf(out, "  movslq %%eax, %%rax\n");
                    }
                    fprintf(out, "  movq %%rax, -%d(%%rbp)\n", vreg_offset(vreg_base, in->dst));
                    break;

                case IR_ADD:
                case IR_SUB:
                case IR_MUL:
                case IR_DIV:
                case IR_MOD:
                case IR_BITAND:
                case IR_BITOR:
                case IR_BITXOR:
                case IR_SHL:
                case IR_SHR: {
                    fprintf(out, "  movq -%d(%%rbp), %%rax\n", vreg_offset(vreg_base, in->src1));
                    fprintf(out, "  movq -%d(%%rbp), %%rcx\n", vreg_offset(vreg_base, in->src2));
                    switch (in->op) {
                        case IR_ADD: fprintf(out, "  addq %%rcx, %%rax\n"); break;
                        case IR_SUB: fprintf(out, "  subq %%rcx, %%rax\n"); break;
                        case IR_MUL: fprintf(out, "  imulq %%rcx, %%rax\n"); break;
                        case IR_DIV:
                        case IR_MOD:
                            if (in->mem_size == 4) {
                                if (in->is_unsigned) {
                                    fprintf(out, "  xorl %%edx, %%edx\n");
                                    fprintf(out, "  divl %%ecx\n");
                                } else {
                                    fprintf(out, "  cltd\n");
                                    fprintf(out, "  idivl %%ecx\n");
                                }
                                if (in->op == IR_MOD) fprintf(out, "  movl %%edx, %%eax\n");
                                if (!in->is_unsigned) fprintf(out, "  movslq %%eax, %%rax\n");
                            } else {
                                if (in->is_unsigned) {
                                    fprintf(out, "  xorq %%rdx, %%rdx\n");
                                    fprintf(out, "  divq %%rcx\n");
                                } else {
                                    fprintf(out, "  cqto\n");
                                    fprintf(out, "  idivq %%rcx\n");
                                }
                                if (in->op == IR_MOD) fprintf(out, "  movq %%rdx, %%rax\n");
                            }
                            break;
                        case IR_BITAND: fprintf(out, "  andq %%rcx, %%rax\n"); break;
                        case IR_BITOR:  fprintf(out, "  orq %%rcx, %%rax\n"); break;
                        case IR_BITXOR: fprintf(out, "  xorq %%rcx, %%rax\n"); break;
                        case IR_SHL:
                            if (in->mem_size == 4) fprintf(out, "  shll %%cl, %%eax\n");
                            else fprintf(out, "  shlq %%cl, %%rax\n");
                            break;
                        case IR_SHR:
                            if (in->mem_size == 4) {
                                fprintf(out, "  %s %%cl, %%eax\n", in->is_unsigned ? "shrl" : "sarl");
                            } else {
                                fprintf(out, "  %s %%cl, %%rax\n", in->is_unsigned ? "shrq" : "sarq");
                            }
                            break;
                        default: break;
                    }
                    fprintf(out, "  movq %%rax, -%d(%%rbp)\n", vreg_offset(vreg_base, in->dst));
                    break;
                }

                case IR_OBF_MBA_ADD: {
                    fprintf(out, "  movq -%d(%%rbp), %%rax\n", vreg_offset(vreg_base, in->src1));
                    fprintf(out, "  movq -%d(%%rbp), %%rcx\n", vreg_offset(vreg_base, in->src2));
                    fprintf(out, "  movabsq $%lld, %%r10\n", (long long)in->obf_key);
                    fprintf(out, "  movq %%rax, %%rdx\n");
                    fprintf(out, "  xorq %%rcx, %%rdx\n");
                    fprintf(out, "  xorq %%r10, %%rdx\n");
                    fprintf(out, "  andq %%rcx, %%rax\n");
                    fprintf(out, "  shlq $1, %%rax\n");
                    fprintf(out, "  xorq %%r10, %%rdx\n");
                    fprintf(out, "  addq %%rdx, %%rax\n");
                    fprintf(out, "  movq %%rax, -%d(%%rbp)\n", vreg_offset(vreg_base, in->dst));
                    break;
                }

                case IR_OBF_MBA_SUB: {
                    fprintf(out, "  movq -%d(%%rbp), %%rax\n", vreg_offset(vreg_base, in->src1));
                    fprintf(out, "  movq -%d(%%rbp), %%rcx\n", vreg_offset(vreg_base, in->src2));
                    fprintf(out, "  movabsq $%lld, %%r10\n", (long long)in->obf_key);
                    fprintf(out, "  movq %%rcx, %%rdx\n");
                    fprintf(out, "  notq %%rdx\n");
                    fprintf(out, "  andq %%rax, %%rdx\n"); /* x & ~y */
                    fprintf(out, "  xorq %%r10, %%rdx\n");
                    fprintf(out, "  notq %%rax\n");
                    fprintf(out, "  andq %%rcx, %%rax\n"); /* ~x & y */
                    fprintf(out, "  xorq %%r10, %%rdx\n");
                    fprintf(out, "  subq %%rax, %%rdx\n");
                    fprintf(out, "  movq %%rdx, -%d(%%rbp)\n", vreg_offset(vreg_base, in->dst));
                    break;
                }

                case IR_OBF_MBA_XOR: {
                    fprintf(out, "  movq -%d(%%rbp), %%rax\n", vreg_offset(vreg_base, in->src1));
                    fprintf(out, "  movq -%d(%%rbp), %%rcx\n", vreg_offset(vreg_base, in->src2));
                    fprintf(out, "  movabsq $%lld, %%r10\n", (long long)in->obf_key);
                    fprintf(out, "  movq %%rax, %%rdx\n");
                    fprintf(out, "  orq %%rcx, %%rdx\n");
                    fprintf(out, "  addq %%r10, %%rdx\n");
                    fprintf(out, "  andq %%rcx, %%rax\n");
                    fprintf(out, "  addq %%r10, %%rax\n");
                    fprintf(out, "  subq %%rax, %%rdx\n");
                    fprintf(out, "  movq %%rdx, -%d(%%rbp)\n", vreg_offset(vreg_base, in->dst));
                    break;
                }

                case IR_OBF_OPAQUE_TRUE:
                case IR_OBF_OPAQUE_FALSE: {
                    if (in->src1 >= 0) {
                        fprintf(out, "  movq -%d(%%rbp), %%rax\n", vreg_offset(vreg_base, in->src1));
                    } else {
                        fprintf(out, "  movq %%rbp, %%rax\n");
                    }
                    fprintf(out, "  movabsq $%lld, %%rcx\n", (long long)in->obf_key);
                    fprintf(out, "  xorq %%rcx, %%rax\n");
                    fprintf(out, "  leaq 1(%%rax), %%rdx\n");
                    fprintf(out, "  imulq %%rdx, %%rax\n");
                    fprintf(out, "  testq $1, %%rax\n");
                    fprintf(out, "  %s %%al\n", (in->op == IR_OBF_OPAQUE_TRUE) ? "sete" : "setne");
                    fprintf(out, "  movzbq %%al, %%rax\n");
                    fprintf(out, "  movq %%rax, -%d(%%rbp)\n", vreg_offset(vreg_base, in->dst));
                    break;
                }

                case IR_OBF_JUNK: {
                    if (in->src1 >= 0) {
                        fprintf(out, "  movq -%d(%%rbp), %%rax\n", vreg_offset(vreg_base, in->src1));
                    } else {
                        fprintf(out, "  movq %%rsp, %%rax\n");
                    }
                    fprintf(out, "  movabsq $%lld, %%rcx\n", (long long)in->obf_key);
                    fprintf(out, "  xorq %%rcx, %%rax\n");
                    fprintf(out, "  rorq $13, %%rax\n");
                    fprintf(out, "  xorq %%rax, %%rax\n");
                    break;
                }

                case IR_EQ:
                case IR_NE:
                case IR_LT:
                case IR_LE:
                case IR_GT:
                case IR_GE: {
                    fprintf(out, "  movq -%d(%%rbp), %%rax\n", vreg_offset(vreg_base, in->src1));
                    fprintf(out, "  movq -%d(%%rbp), %%rcx\n", vreg_offset(vreg_base, in->src2));
                    if (in->mem_size == 4) {
                        fprintf(out, "  cmpl %%ecx, %%eax\n");
                    } else {
                        fprintf(out, "  cmpq %%rcx, %%rax\n");
                    }
                    const char *set_inst = "sete";
                    switch (in->op) {
                        case IR_EQ: set_inst = "sete"; break;
                        case IR_NE: set_inst = "setne"; break;
                        case IR_LT: set_inst = in->is_unsigned ? "setb" : "setl"; break;
                        case IR_LE: set_inst = in->is_unsigned ? "setbe" : "setle"; break;
                        case IR_GT: set_inst = in->is_unsigned ? "seta" : "setg"; break;
                        case IR_GE: set_inst = in->is_unsigned ? "setae" : "setge"; break;
                        default: break;
                    }
                    fprintf(out, "  %s %%al\n", set_inst);
                    fprintf(out, "  movzbq %%al, %%rax\n");
                    fprintf(out, "  movq %%rax, -%d(%%rbp)\n", vreg_offset(vreg_base, in->dst));
                    break;
                }

                case IR_JMP:
                    fprintf(out, "  jmp .L%d\n", in->label);
                    break;

                case IR_JZ:
                    fprintf(out, "  movq -%d(%%rbp), %%rax\n", vreg_offset(vreg_base, in->src1));
                    fprintf(out, "  cmpq $0, %%rax\n");
                    fprintf(out, "  je .L%d\n", in->label);
                    break;

                case IR_JNZ:
                    fprintf(out, "  movq -%d(%%rbp), %%rax\n", vreg_offset(vreg_base, in->src1));
                    fprintf(out, "  cmpq $0, %%rax\n");
                    fprintf(out, "  jne .L%d\n", in->label);
                    break;

                case IR_ARG:
                    if (in->imm >= 0 && in->imm < 64) {
                        pending_args[in->imm] = in->src1;
                        if (in->imm + 1 > pending_arg_count) {
                            pending_arg_count = (int)in->imm + 1;
                        }
                    }
                    break;

                case IR_CALL: {
                    int argc = in->call_arg_count;
                    int reg_limit = target->is_windows ? 4 : 6;
                    int reg_args = argc < reg_limit ? argc : reg_limit;
                    int stack_args = argc > reg_limit ? (argc - reg_limit) : 0;
                    int shadow_space = target->is_windows ? 32 : 0;
                    int stack_bytes = align16(shadow_space + stack_args * 8);

                    if (stack_bytes > 0) {
                        fprintf(out, "  subq $%d, %%rsp\n", stack_bytes);
                        for (int a = 0; a < stack_args; a++) {
                            int vreg = pending_args[reg_limit + a];
                            fprintf(out, "  movq -%d(%%rbp), %%rax\n", vreg_offset(vreg_base, vreg));
                            fprintf(out, "  movq %%rax, %d(%%rsp)\n", shadow_space + a * 8);
                        }
                    }
                    for (int a = 0; a < reg_args; a++) {
                        int vreg = pending_args[a];
                        fprintf(out, "  movq -%d(%%rbp), %s\n", vreg_offset(vreg_base, vreg), arg_regs[a]);
                    }
                    if (!target->is_windows) {
                        fprintf(out, "  movb $0, %%al\n");
                    }
                    fprintf(out, "  callq %s%s\n", target->symbol_prefix, in->sym_name);
                    if (stack_bytes > 0) {
                        fprintf(out, "  addq $%d, %%rsp\n", stack_bytes);
                    }
                    if (in->dst >= 0) {
                        fprintf(out, "  movq %%rax, -%d(%%rbp)\n", vreg_offset(vreg_base, in->dst));
                    }
                    pending_arg_count = 0;
                    break;
                }

                case IR_RET:
                    if (in->src1 >= 0) {
                        fprintf(out, "  movq -%d(%%rbp), %%rax\n", vreg_offset(vreg_base, in->src1));
                    }
                    fprintf(out, "  movq %%rbp, %%rsp\n");
                    fprintf(out, "  popq %%rbp\n");
                    fprintf(out, "  retq\n");
                    break;
            }
        }
        fprintf(out, "\n");
    }

    if (target->is_linux) {
        fprintf(out, "  .section .note.GNU-stack,\"\",@progbits\n");
    }
}
